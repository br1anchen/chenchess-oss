export type ChenIconName =
  | IconName
  | Exclude<keyof typeof chenChessIcons, number | symbol>

export type ChenIconProps = Omit<IconProps, "icon"> & { icon: ChenIconName }

/**
 * Astryx's Icon with the registry widened to the ChenChess glyphs. The cast is
 * the widening `ExtendedIconName` already permits at the registry layer;
 * Astryx's prop type just doesn't carry it.
 */
export function Icon({ icon, ...props }: ChenIconProps) {
  // SAFETY: every ChenIconName outside the built-in union is registered on the
  // module's `registerIcons` call above, which is exactly the widening the
  // registry's `ExtendedIconName` contract permits.
  return <AstryxIcon {...props} icon={icon as IconName} />
}
